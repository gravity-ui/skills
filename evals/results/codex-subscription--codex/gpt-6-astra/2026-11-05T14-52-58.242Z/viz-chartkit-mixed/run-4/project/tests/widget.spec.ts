import {test, expect} from '@playwright/test';

test('loads each engine on demand and supports period, comparison, export and persistence', async ({page}) => {
  const requests: string[] = [];
  const errors: string[] = [];
  page.on('request',req=>requests.push(req.url()));
  page.on('pageerror',err=>errors.push(err.message));
  await page.goto('/');
  await expect(page.locator('.recharts-surface')).toBeVisible();
  await expect(page.locator('.recharts-area-curve')).toBeVisible();
  expect(requests.some(url=>/SalesEngine-.*\.js/.test(url))).toBe(true);
  expect(requests.some(url=>/MonitoringEngine-.*\.js/.test(url))).toBe(false);
  await page.waitForTimeout(650);
  await page.screenshot({path:'/tmp/pulse-desktop.png',fullPage:true});
  await page.getByRole('tab',{name:'Мониторинг'}).click();
  await expect(page.locator('.uplot canvas')).toBeVisible();
  expect(requests.some(url=>/MonitoringEngine-.*\.js/.test(url))).toBe(true);
  await expect(page.locator('.metric').nth(1)).toContainText('14');
  await page.getByRole('button',{name:'Последние 24 ч',exact:true}).click();
  await page.getByRole('button',{name:'Последние 1 ч',exact:true}).click();
  await expect(page.locator('.metric').nth(1)).toContainText('600');
  await page.getByRole('button',{name:'Базовый уровень',exact:true}).click();
  await expect(page.getByRole('button',{name:'Базовый уровень',exact:true})).toHaveAttribute('aria-pressed','false');
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Экспорт',exact:true}).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('pulse-monitoring-1h.csv');
  const stream=await download.createReadStream();
  let csv='';for await(const chunk of stream!) csv+=chunk.toString();
  expect(csv.trim().split('\n')).toHaveLength(601);
  expect(csv).not.toContain('Базовый уровень');
  await page.reload();
  await expect(page.getByRole('tab',{name:'Мониторинг'})).toHaveAttribute('aria-selected','true');
  await expect(page.locator('.uplot canvas')).toBeVisible();
  await page.getByRole('tab',{name:'Продажи',exact:true}).click();
  await expect(page.locator('.recharts-surface')).toBeVisible();
  await expect(page.locator('.recharts-area-curve')).toBeVisible();
  await page.getByRole('button',{name:'Последние 30 дней',exact:true}).click();
  await page.getByRole('button',{name:'Последние 7 дней',exact:true}).click();
  await expect(page.locator('.widget-footer')).toContainText('7 точек данных');
  await page.getByRole('button',{name:'Развернуть график'}).click();
  await expect(page.locator('.visualization-card')).toHaveClass(/fullscreen/);
  await page.keyboard.press('Escape');
  await expect(page.locator('.visualization-card')).not.toHaveClass(/fullscreen/);
  expect(errors).toEqual([]);
});

test('fits a mobile screen in both modes', async ({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await expect(page.locator('.recharts-surface')).toBeVisible();
  await expect(page.locator('.recharts-area-curve')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.waitForTimeout(650);
  await page.screenshot({path:'/tmp/pulse-mobile.png',fullPage:true});
  await page.getByRole('tab',{name:'Мониторинг'}).click();
  await expect(page.locator('.uplot canvas')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
});
